    methods (Test)
        function savedSessionsRetainTab2Results(testCase)
            % Values were generated with the unmodified Tab 2 models at
            % 298.15 K. The tolerance covers deterministic ODE interpolation
            % differences without masking engineering-result regressions.
            expected = NirpMicromixingGoldenMasterTest.expectedResults() ;
            root = fileparts(fileparts(mfilename('fullpath'))) ;
            for k = 1:numel(expected)
                loaded = load(fullfile(root,'saves',expected(k).file), ...
                    'sessionData') ;
                session = loaded.sessionData ;
                rtd = NirpMicromixingGoldenMasterTest.restoreRtd( ...
                    session.shared.rtd) ;
                rs = NirpMicromixingGoldenMasterTest.restoreValueObject( ...
                    session.prediction.rs,'ReactionSys') ;
                feed = NirpMicromixingGoldenMasterTest.restoreValueObject( ...
                    session.prediction.feedStream,'Stream') ;
                C0 = feed.concentration(:)' ;

                segregation = SegregationModel(rtd) ;
                segregation = segregation.compute_isothermal(rs,C0) ;
                maximumMixedness = MaxMixednessModel(rtd) ;
                maximumMixedness = maximumMixedness.compute_isothermal(rs,C0) ;

                testCase.verifyEqual(segregation.C_exit,expected(k).Cseg, ...
                    'RelTol',2e-9,'AbsTol',1e-10,expected(k).file) ;
                testCase.verifyEqual(segregation.X_mean,expected(k).Xseg, ...
                    'RelTol',2e-9,'AbsTol',1e-10,expected(k).file) ;
                testCase.verifyEqual(maximumMixedness.C_exit,expected(k).Cmm, ...
                    'RelTol',2e-9,'AbsTol',1e-10,expected(k).file) ;
                testCase.verifyEqual(maximumMixedness.X_exit,expected(k).Xmm, ...
                    'RelTol',2e-9,'AbsTol',1e-10,expected(k).file) ;
            end
        end
    end

    methods (Static, Access = private)
        function obj = restoreValueObject(snapshot,className)
            obj = feval(className) ;
            names = fieldnames(snapshot) ;
            for k = 1:numel(names)
                name = names{k} ;
                if isprop(obj,name)
                    try
                        obj.(name) = snapshot.(name) ;
                    catch
                    end
                end
            end
        end

        function obj = restoreRtd(snapshot)
            obj = RTD(snapshot.t,snapshot.Et) ;
            if isfield(snapshot,'source'), obj.source = snapshot.source ; end
            if isfield(snapshot,'modelInfo'), obj.modelInfo = snapshot.modelInfo ; end
        end

