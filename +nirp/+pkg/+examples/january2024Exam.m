function pkg = january2024Exam()
%JANUARY2024EXAM Return the reactive package for the January 2024 exam.
%   The third reaction is 2 A -> D + E, as required to reproduce the
%   professor's reported equal D and E concentrations.
% =========================================================================
% Javier Berenguer Sabater
% Created: November 3, 2026. Last update: November 3, 2026
% =========================================================================

    pkg.meta = struct('formatVersion',1,'name',"Exam January 2024", ...
        'thermodynamics',false) ;
    cp = struct('type',"constant",'value',1,'unit',"J/(mol*K)") ;
    pkg.components = struct('name',{"A","B","C","D","E"}, ...
        'Mw',{[],[],[],[],[]},'cp',{cp,cp,cp,cp,cp}, ...
        'hf',{[],[],[],[],[]}) ;
    pkg.reactions.stoich = [-1 1 0 0 0;0 -1 1 0 0; ...
        -2 0 0 1 1;0 1 0 -1 -1] ;
    pkg.reactions.DH = struct('value',zeros(1,4),'unit',"J/mol") ;
    pkg.reactions.Tref = struct('value',298.15,'unit',"K") ;
    pkg.reactions.rateUnits = struct('concentration',"mol/m^3", ...
        'time',"s") ;
    expressions = {"concentration(1)-2*concentration(2)", ...
        "concentration(2)","0.01*concentration(1)^2", ...
        "0.001*concentration(4)*concentration(5)"} ;
    common = struct('type',"expression",'k0',[],'Ea',[],'orders',[], ...
        'reverse',[],'expression',"") ;
    pkg.reactions.kinetics = repmat(common,1,4) ;
    for i = 1:4
        pkg.reactions.kinetics(i).expression = expressions{i} ;
    end
    feed = struct('name',"F1",'phase',"L", ...
        'T',struct('value',298.15,'unit',"K"), ...
        'P',struct('value',101325,'unit',"Pa"), ...
        'basis',"concentrations",'values',[1000 0 0 0 0], ...
        'valuesUnit',"mol/m^3", ...
        'Q',struct('value',0.05,'unit',"m^3/s")) ;
    pkg.feeds = repmat(feed,1,3) ;
    pkg.feeds(2).name = "Segregation feed" ;
    pkg.feeds(3).name = "Maximum mixedness feed" ;
    nirp.pkg.validate(pkg) ;
end
