function pkg = nonIdealSecondOrder()
%NONIDEALSECONDORDER Return the SI second-order non-ideal example package.
%   The liquid feed has C_A0 = 10 mol/m^3 and -r_A = 0.05*C_A^2, so a
%   two-second reactor has Damkohler number k*tau*C_A0 = 1.
% =========================================================================
% Javier Berenguer Sabater
% Created: November 3, 2026. Last update: November 3, 2026
% =========================================================================

    pkg.meta = struct('formatVersion',1, ...
        'name',"Non-ideal second-order reference") ;
    cp = struct('type',"constant",'value',1,'unit',"J/(mol*K)") ;
    pkg.components = struct('name',{"A","P"},'Mw',{[],[]}, ...
        'cp',{cp,cp},'hf',{[],[]}) ;
    pkg.reactions.stoich = [-1 1] ;
    pkg.reactions.DH = struct('value',0,'unit',"J/mol") ;
    pkg.reactions.Tref = struct('value',298.15,'unit',"K") ;
    pkg.reactions.rateUnits = struct('concentration',"mol/m^3", ...
        'time',"s") ;
    pkg.reactions.kinetics = struct('type',"powerlaw",'k0',0.05, ...
        'Ea',struct('value',0,'unit',"J/mol"),'orders',[2 0], ...
        'reverse',[],'expression',"") ;
    feed = struct('name',"F1",'phase',"L", ...
        'T',struct('value',298.15,'unit',"K"), ...
        'P',struct('value',101325,'unit',"Pa"), ...
        'basis',"concentrations",'values',[10 0], ...
        'valuesUnit',"mol/m^3", ...
        'Q',struct('value',1,'unit',"m^3/s")) ;
    names = ["F1","Segregation feed","Maximum mixedness feed", ...
        "Ideal feed","Non-ideal feed"] ;
    pkg.feeds = repmat(feed,1,numel(names)) ;
    for i = 1:numel(names), pkg.feeds(i).name = names(i) ; end
    nirp.pkg.validate(pkg) ;
end
