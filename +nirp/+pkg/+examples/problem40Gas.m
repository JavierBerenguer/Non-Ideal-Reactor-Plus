function pkg = problem40Gas()
%PROBLEM40GAS Return the package for collection problem 40.
%   PKG = nirp.pkg.examples.problem40Gas() describes A + B -> C with an
%   inert gas at 227 C and 10 atm. Its expression embeds the original
%   feed constants and needs no global state.
%   Example: pkg = nirp.pkg.examples.problem40Gas().
% =========================================================================
% Javier Berenguer Sabater
% Created: October 1, 2026. Last update: October 1, 2026
% =========================================================================

    pkg.meta = struct('formatVersion',1,'name',"Problem 40 gas") ;
    cp = struct('type',"constant",'value',1,'unit',"J/(mol*K)") ;
    pkg.components = struct('name',{"A","B","C","Inert"}, ...
        'Mw',{[],[],[],[]},'cp',{cp,cp,cp,cp},'hf',{[],[],[],[]}) ;
    pkg.reactions.stoich = [-1 -1 1 0] ;
    pkg.reactions.DH = struct('value',0,'unit',"J/mol") ;
    pkg.reactions.Tref = struct('value',227,'unit',"C") ;
    pkg.reactions.rateUnits = struct('concentration',"mol/L", ...
        'time',"min") ;
    totalFlow = 10*101325*1e-3/(8.314*(227+273.15)) ;
    nA0 = 0.41*totalFlow ;
    expression = sprintf(['0.0167-0.023*((concentration(1)*1e3*1e-3-' ...
        '%.17g)*1013250/(%.17g*(concentration(1)*1e3*8.314*500.15-' ...
        '1013250))-0.1)+0.0234*((concentration(1)*1e3*1e-3-' ...
        '%.17g)*1013250/(%.17g*(concentration(1)*1e3*8.314*500.15-' ...
        '1013250))-0.1)*((concentration(1)*1e3*1e-3-' ...
        '%.17g)*1013250/(%.17g*(concentration(1)*1e3*8.314*500.15-' ...
        '1013250))-0.7)'],nA0,nA0,nA0,nA0,nA0,nA0) ;
    pkg.reactions.kinetics = struct('type',"expression",'k0',[], ...
        'Ea',[],'orders',[],'reverse',[],'expression',string(expression)) ;
    pkg.feeds = struct('name',"F1",'phase',"G", ...
        'T',struct('value',227,'unit',"C"), ...
        'P',struct('value',10,'unit',"atm"), ...
        'basis',"totalAndFractions", ...
        'values',[totalFlow 0.41 0.41 0 0.18], ...
        'valuesUnit',"mol/s",'Q',struct('value',1,'unit',"L/s")) ;
    nirp.pkg.validate(pkg) ;
end
