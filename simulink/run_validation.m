function [product,purge,recycle] = separatorRecycleLoop(volume)
    % Successive-substitution reference for the separator recycle examples.
    pkg = nirp.pkg.examples.firstOrderLiquid() ;
    rs = nirp.pkg.toReactionSys(pkg) ; feed = nirp.pkg.feedStream(pkg,"F1") ;
    recycle = nirp.stream.empty(rs.nComponents,feed.T,feed.P,0) ;
    for iteration = 1:5000
        mixed = nirp.units.mixer(struct(),{feed,recycle},rs) ;
        outlet = nirp.units.cstr(struct('V',volume, ...
            'heatMode','Isothermal'),mixed,rs) ;
        separated = nirp.units.separator(struct('recovery',[0.95 0.02]), ...
            outlet,rs) ;
        split = nirp.units.splitter(struct('fractions',[0.1 0.9]), ...
            separated{1},rs) ;
        change = max(abs(split{2}.F-recycle.F)) ; recycle = split{2} ;
        if change < 1e-15*max(1,max(abs(recycle.F))), break, end
    end
    product = separated{2} ; purge = split{1} ;
end

function value = separatorRecycleProductA(volume)
    product = separatorRecycleLoop(volume) ; value = product.F(1) ;
end

